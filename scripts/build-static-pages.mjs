function renderContentBlock(block, locale = "ja") {
    if (block.type === "paragraph") {
        return `                <p>${escapeHtml(block.text)}</p>`;
    }

    if (block.type === "subheading") {
        return `                <h3>${escapeHtml(block.text)}</h3>`;
    }

    if (block.type === "list") {
        return `                <ul>
${block.items.map((item) => `                    <li>${escapeHtml(item)}</li>`).join("\n")}
                </ul>`;
    }

    if (block.type === "email") {
        const mailto = block.mailto || block.value;
        return `                <p class="${escapeAttribute(block.className || "email")}">
                    ${escapeHtml(block.label || "Email")}: <a href="mailto:${escapeAttribute(mailto)}">${escapeHtml(block.value)}</a>
                </p>`;
    }

    if (block.type === "link") {
        const href = resolveContentHref(block.href, locale);
        return `                <p class="${escapeAttribute(block.className || "content-link")}">
                    ${block.label ? `<span>${escapeHtml(block.label)}:</span> ` : ""}<a href="${escapeAttribute(href)}">${escapeHtml(block.text || block.href)}</a>
                </p>`;
    }

    throw new Error(`Unsupported content block type "${block.type}"`);
}

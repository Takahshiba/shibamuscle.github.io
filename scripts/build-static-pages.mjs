function buildStaticContentKeywords(page) {
    const values = [
        page.heading,
        ...(page.sections || []).map((section) => section.heading)
    ].filter(Boolean);
    const seen = new Set();

    return values.filter((value) => {
        if (seen.has(value)) {
            return false;
        }
        seen.add(value);
        return true;
    });
}


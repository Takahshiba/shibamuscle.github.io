const catalog = loadCatalog();
const discovery = loadDiscovery();
const pages = loadPages();
const locales = getGeneratedLocales();
const APP_THEME_COLOR = "#ff7a00";
assertExpectedLocales(locales);

let generatedPages = 0;

for (const locale of locales) {
    if (locale.outputDir) {
        ensureDirectory(join(process.cwd(), locale.outputDir));
    }

    for (const sourcePage of pages) {
        const page = isEnglishOnlyAppPage(sourcePage)
            ? englishOnlyPage(sourcePage)
            : localizeStaticPage(sourcePage, locale.code);
        let html = "";

        if (page.kind === "home") {
            html = renderHomePage(page, catalog, locale.code);
        } else if (page.kind === "content") {
            html = renderContentPage(page, locale.code);
        } else {
            throw new Error(`Unsupported page kind "${page.kind}" in ${page.file}`);
        }

        writeFileSync(buildOutputPath(page.file, locale.code), html);
        generatedPages += 1;
    }
}

console.log(`Generated ${generatedPages} localized static pages from src/pages/.`);

function assertExpectedLocales(locales) {
    const localeCodes = locales.map((locale) => locale.code);
    const requiredLocales = ["ja", "ko", "zh-hant", "zh-hans", "es", "fr", "de"];
    const missingLocales = requiredLocales.filter((locale) => !localeCodes.includes(locale));

    if (missingLocales.length) {
        throw new Error(`${missingLocales.join(", ")} locale(s) are required for this build. Active locales: ${localeCodes.join(", ")}`);
    }
}

function isEnglishOnlyAppPage(page) {
    return page.appShell === true;
}

function englishOnlyPage(page) {
    const { locales, ...basePage } = page;
    return basePage;
}


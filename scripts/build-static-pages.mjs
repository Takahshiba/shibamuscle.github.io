function buildHomePreviewCards(catalogData, locale, unit, assetLocale = locale) {
    const preferredSlugs = ["bench-press", "squat", "deadlift", "lat-pulldown", "dumbbell-curl", "leg-press"];
    const allCards = catalogData.sections.flatMap((section) => {
        const sectionTitle = locale === "ja" ? section.titles.ja : getCategoryLabel(section, locale);
        return section.cards.map((card) => ({ card, section, sectionTitle }));
    });
    const bySlug = new Map();
    for (const item of allCards) {
        if (!bySlug.has(item.card.slug)) {
            bySlug.set(item.card.slug, item);
        }
    }
    const picked = [];
    const seenSlugs = new Set();
    const seenNames = new Set();
    const addCard = (item) => {
        if (!item || picked.length >= 6 || seenSlugs.has(item.card.slug)) {
            return;
        }
        const localizedCard = buildLocalizedCard(item.card, item.section, locale);
        const name = locale === "en"
            ? titleFromSlug(item.card.slug) || localizedCard.names?.en || localizedCard.names?.ja || ""
            : localizedCard.names?.[locale] || localizedCard.names?.ja || titleFromSlug(item.card.slug) || "";
        const normalizedName = normalizePreviewName(name);
        if (normalizedName && seenNames.has(normalizedName)) {
            return;
        }
        picked.push({ ...item, localizedCard, name });
        seenSlugs.add(item.card.slug);
        seenNames.add(normalizedName);
    };
    preferredSlugs.forEach((slug) => addCard(bySlug.get(slug)));
    allCards.forEach(addCard);

    return picked.map(({ card, section, sectionTitle, localizedCard, name }) => {
        return {
            href: `${unit}_${card.slug}.html`,
            image: assetHref(card.image, assetLocale),
            name,
            category: locale === "en"
                ? englishCategoryLabel(section.id)
                : localizedCard.categories?.[locale] || localizedCard.categories?.ja || sectionTitle || englishCategoryLabel(section.id)
        };
    });
}

function normalizePreviewName(name) {
    return String(name || "").replace(/\s+/g, "").toLowerCase();
}

function titleFromSlug(slug) {
    const smallWords = new Set(["and", "or", "to"]);
    return slug.split("-").map((part, index) => {
        if (index > 0 && smallWords.has(part)) {
            return part;
        }
        return part.charAt(0).toUpperCase() + part.slice(1);
    }).join(" ");
}

function englishCategoryLabel(sectionId) {
    const labels = {
        "whole-body-section": "Full Body",
        "chest-section": "Chest",
        "back-section": "Back",
        "shoulder-section": "Shoulders",
        "arm-section": "Arms",
        "leg-section": "Legs",
        "core-section": "Core"
    };

    return labels[sectionId] || "Exercise";
}

